    lines.append(f"    background = {colorLit(bg)}, surface = {colorLit(card)},")
    lines.append(f"    surfaceHigh = {colorLit(hover)}, accent = {colorLit(accent)},")
    lines.append(f"    onAccent = {onaccent},")
    lines.append(f"    text = {colorLit(text)}, textMuted = {colorLit(muted)},")
