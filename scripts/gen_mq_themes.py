#!/usr/bin/env python3
"""Generate MqThemes.kt: EXACT web palette port (themes.ts → Compose).
All 23 themes, hex-identical, plus the web type scale (mq-t-* → Manrope)
and web radius/spacing tokens. Central design system for visual parity."""
import re

src = open("/home/z/my-project/src/lib/themes.ts").read()
# strip ALL comments (full-line + trailing). Safe: no string literal in this
# file contains "//" (hex/rgba/gradient values only — verified above).
clean = re.sub(r"//[^\n]*", "", src)

themes = re.findall(
    r'([\w-]+):\s*\{\s*id:\s*"([\w-]+)",\s*name:\s*"([^"]+)",\s*'
    r'background:\s*"([^"]+)",\s*card:\s*"([^"]+)",\s*cardHover:\s*"([^"]+)",\s*'
    r'accent:\s*"([^"]+)",\s*text:\s*"([^"]+)",\s*textMuted:\s*"([^"]+)",\s*'
    r'border:\s*"([^"]+)",\s*inputBg:\s*"([^"]+)",\s*playerBg:\s*"([^"]+)",\s*'
    r'navBg:\s*"([^"]+)"', clean)

assert len(themes) == 23, f"expected 23 themes, got {len(themes)}"

def c(hexstr):
    h = hexstr.lstrip("#")
    if len(h) == 6:
        return f"Color(0xFF{h.upper()})"
    if len(h) == 8:  # CSS #RRGGBBAA → Compose ARGB
        return f"Color(0x{h[6:8].upper()}{h[0:6].upper()})"
    raise ValueError(hexstr)

def colorLit(s):
    """Any CSS color in themes.ts → Kotlin Color literal (hex or rgba)."""
    s = s.strip()
    if s.startswith("#"):
        return c(s)
    m = re.fullmatch(r"rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)", s)
    if m:
        r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
        ai = round(a * 255)
        return f"Color(0x{ai:02X}{r:02X}{g:02X}{b:02X})"
    raise ValueError(s)

def ident(key):
    # Kotlin object name per theme (CamelCase of web name)
    return "".join(p.capitalize() for p in re.split(r"[-_]", key))

